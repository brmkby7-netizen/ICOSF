#!/usr/bin/env node
// Bundles the filter compiler into a single IIFE (global `BastionCompiler`)
// that the apps load into a WKWebView, and copies the filter catalog next to it.
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFiles = [path.join(root, 'dist/bastion-compiler.js'), path.join(root, 'apple/App/Resources/bastion-compiler.js')];

const result = await build({
  entryPoints: [path.join(root, 'compiler/src/index.js')],
  bundle: true,
  format: 'iife',
  globalName: 'BastionCompiler',
  target: ['safari15'],
  write: false,
  legalComments: 'none',
  banner: { js: '/* Bastion filter compiler — generated by scripts/build-compiler.mjs; do not edit. */' },
});
for (const out of outFiles) {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, result.outputFiles[0].text);
  console.log('wrote', path.relative(root, out), (result.outputFiles[0].text.length / 1024).toFixed(1) + ' KB');
}
fs.copyFileSync(path.join(root, 'filters/catalog.json'), path.join(root, 'apple/App/Resources/catalog.json'));
console.log('copied filters/catalog.json -> apple/App/Resources/catalog.json');
